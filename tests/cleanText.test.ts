import { describe, expect, test } from "bun:test"
import { cleanText } from "../src/index"

// Таблица — заодно документация поведения чистильщика: что именно
// вырезается, а что (например, «ну» и «мама») принципиально не трогается.
describe("cleanText", () => {
    const cases: Array<[string, string, string]> = [
        ["схлопывание пробелов + капитализация", "  привет   мир  ", "Привет мир."],
        ["слова-паразиты", "ээ короче говоря сделай эм задачу", "Сделай задачу."],
        ["невербальные блоки построчно", "[музыка]\nтекст\n(шум)", "Текст."],
        ["невербальные блоки инлайн", "текст [музыка] продолжение", "Текст продолжение."],
        ["«новая строка»", "привет новая строка мир", "Привет.\nМир."],
        ["«абзац»", "первый абзац второй", "Первый.\nВторой."],
        ["«отступ»", "сделай отступ икс", "Сделай \t икс."],
        ["звёздочки-маркеры", "*первое* второе", "Первое второе."],
        ["одиночное «ну» не удаляется", "ну сделай", "Ну сделай."],
        ["«м{2,}» не задевает «мама»", "мама мыла раму", "Мама мыла раму."],
        ["конечная пунктуация не дублируется (?)", "как дела?", "Как дела?"],
        ["конечная пунктуация не дублируется (:)", "вот так:", "Вот так:"],
        ["CRLF от whisper", "привет\r\nмир", "Привет мир."],
        ["пустой ввод", "", ""],
        ["только пробелы", "   ", ""],
    ]

    for (const [name, input, expected] of cases) {
        test(name, () => {
            expect(cleanText(input)).toBe(expected)
        })
    }
})
